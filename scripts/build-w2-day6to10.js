// 메인 실행
// ============================================================
function main() {
  const BASE = path.resolve(__dirname, '..');
  const batchPath = path.join(BASE, 'generated', 'daily-batch-reading-wittgenstein2.json');
  const staticDir = path.join(BASE, 'frontend', 'public', 'daily-reading', 'wittgenstein2');

  console.log('비트겐슈타인2 Day 6~10 빌드 시작...\n');

  const results = [
    buildDay6(),
    buildDay7(),
    buildDay8(),
    buildDay9(),
    buildDay10()
  ];

  // 글자수 검증
  for (const r of results) {
    const dayIdx = r.batchItem.day_index;
    const paras = r.content.payload.passage.paragraphs;
    const len = paras.reduce((s, p) => s + p.text.length, 0);
    const cards = r.content.payload.recall.cards;
    const confirms = r.content.payload.confirm.questions;
    const steps = r.content.payload.intensive.timeline;

    if (len < 1450 || len > 1550) {
      console.error(`  [오류] Day ${dayIdx}: 글자수 ${len}자 (목표 1450~1550)`);
    } else {
      console.log(`  [OK] Day ${dayIdx}: ${len}자, 정독 ${steps.length}스텝, 복기 ${cards.length}장, 확인 ${confirms.length}문항`);
    }

    if (cards.length !== 8) {
      console.error(`  [오류] Day ${dayIdx}: 복기 카드 ${cards.length}장 (목표 8장)`);
    }
  }

  // 배치 파일 다시 읽어서 교체 (다른 에이전트와의 충돌 방지)
  console.log('\n배치 파일 읽기...');
  const batch = JSON.parse(fs.readFileSync(batchPath, 'utf8'));

  for (const r of results) {
    const dayIdx = r.batchItem.day_index;
    const idx = batch.items.findIndex(it => it.day_index === dayIdx && it.level_id === 'WITTGENSTEIN_2');
    if (idx === -1) {
      console.error(`  [오류] 배치에서 Day ${dayIdx} 찾지 못함`);
      continue;
    }
    batch.items[idx] = r.batchItem;
    console.log(`  배치 items[${idx}] (Day ${dayIdx}) 교체 완료`);
  }

  fs.writeFileSync(batchPath, JSON.stringify(batch, null, 2), 'utf8');
  console.log('배치 파일 저장 완료.');

  // static 파일 저장
  for (const r of results) {
    const dayIdx = r.batchItem.day_index;
    const dayStr = String(dayIdx).padStart(3, '0');
    const staticPath = path.join(staticDir, `${dayStr}.json`);
    fs.writeFileSync(staticPath, JSON.stringify(r.content, null, 2), 'utf8');
    console.log(`  static ${dayStr}.json 저장 완료`);
  }

  console.log('\n빌드 완료!');
}

main();

function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`문단 ${pid}를 찾을 수 없음`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText.substring(0,40)}..." not found in ${pid}`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function makeStep(stepId, paragraphs, pid, searchText, prompt, choices, answerId) {
  const range = findRange(paragraphs, pid, searchText);
  return {
    stepId,
    highlight: { ranges: [range] },
    question: {
      prompt,
      choices: choices.map((t, i) => ({ id: String.fromCharCode(65 + i), text: t })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeSummary(stepId, paragraphs, pid, prompt, choices, answerId) {
  const para = paragraphs.find(p => p.id === pid);
  return {
    stepId,
    highlight: { ranges: [{ paragraphId: pid, start: 0, end: para.text.length }] },
    question: {
      prompt,
      choices: choices.map((t, i) => ({ id: String.fromCharCode(65 + i), text: t })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeConfirm(id, prompt, paragraphs, pid, searchText) {
  const range = findRange(paragraphs, pid, searchText);
  return {
    id, prompt,
    answerRanges: [range],
    scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 },
    revealOnWrong: true,
    answerMatchMode: "ANY"
  };
}

function makeRecall(paragraphs) {
  const fullText = paragraphs.map(p => p.text).join('\n');
  const count = 8;
  const cardLen = Math.ceil(fullText.length / count);
  const cards = [];
  for (let i = 0; i < count; i++) {
    const s = i * cardLen;
    const e = Math.min(s + cardLen, fullText.length);
    cards.push({ id: `c${i + 1}`, text: fullText.substring(s, e) });
  }
  return { cards, correctOrder: cards.map(c => c.id), seedPenalty: 1 };
}


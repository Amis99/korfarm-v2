function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`paragraph ${pid} not found`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText.substring(0,30)}..." not found in ${pid}`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function makeContent(day) {
  const isOdd = day.dayIndex % 2 === 1;
  const subArea = isOdd ? 'NONFICTION' : 'LITERATURE';
  const subAreaKo = isOdd ? '비문학' : '문학';
  const padded = String(day.dayIndex).padStart(3, '0');
  const contentId = `dr-w3-${padded}`;

  const fullText = day.paragraphs.map(p => p.text).join('');
  const charCount = fullText.length;

  const paraData = day.paragraphs.map(p => ({ ...p, sentences: findSentences(p.text) }));

  // 정독 타임라인
  const timeline = [];
  let stepNum = 1;
  for (const pd of paraData) {
    for (let si = 0; si < pd.sentences.length; si++) {
      const sent = pd.sentences[si];
      const q = day.intensiveQs.find(q => q.paragraphId === pd.id && q.sentenceIdx === si);
      if (!q) continue;
      timeline.push({
        stepId: `s${stepNum++}`,
        highlight: { ranges: [{ paragraphId: pd.id, start: sent.start, end: sent.end }] },
        question: { prompt: q.prompt, choices: q.choices, answerId: q.answerId,
          scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true } }
      });
    }
    const cq = day.centralQs.find(q => q.paragraphId === pd.id);
    if (cq) {
      timeline.push({
        stepId: `s${stepNum++}`,
        highlight: { ranges: [{ paragraphId: pd.id, start: 0, end: pd.text.length }] },
        question: { prompt: '이 문단의 중심 내용으로 가장 적절한 것은?', choices: cq.choices, answerId: cq.answerId,
          scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true } }
      });
    }
  }

  // 복기 카드 8장
  const totalLen = fullText.length;
  const cardSize = Math.floor(totalLen / 8);
  const cards = [];
  let pos = 0;
  for (let i = 0; i < 8; i++) {
    const end = i === 7 ? totalLen : pos + cardSize;
    cards.push({ id: `c${i+1}`, text: fullText.substring(pos, end) });
    pos = end;
  }

  // 확인 문항
  const confirmQs = day.confirmQs.map((q, i) => {
    const ranges = q.answerTexts.map(at => findRange(day.paragraphs, at.paragraphId, at.text));
    return { id: `q${i+1}`, prompt: q.prompt, answerRanges: ranges,
      scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 }, revealOnWrong: true, answerMatchMode: 'ANY' };
  });

  return {
    content: {
      contentId, contentType: 'DAILY_READING', version: 1, status: 'PUBLISHED',
      title: `일일 독해(비트겐슈타인 3) Day ${day.dayIndex} ${subAreaKo}`,
      description: '일일 독해 - 정독·복기·확인',
      targetLevel: 'WITTGENSTEIN_3', schoolGradeRange: { min: 11, max: 12 },
      area: 'READING', subArea, competencies: ['READING'], tags: ['daily'],
      access: { mode: 'FREE' }, seedReward: { seedType: 'WHEAT', count: 3, multiplier: 1 },
      timeLimitSec: 480, assets: {},
      payload: {
        passage: { format: 'TEXT', paragraphs: day.paragraphs },
        intensive: { timeline },
        recall: { cards, correctOrder: cards.map(c => c.id), seedPenalty: 1 },
        confirm: { questions: confirmQs }
      }
    }, subArea, charCount
  };
}


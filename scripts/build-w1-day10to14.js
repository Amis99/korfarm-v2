function main() {
  const ROOT = path.join(__dirname, '..');
  const BATCH_FILE = path.join(ROOT, 'generated', 'daily-batch-reading-wittgenstein1.json');
  const STATIC_DIR = path.join(ROOT, 'frontend', 'public', 'daily-reading', 'wittgenstein1');

  if (!fs.existsSync(STATIC_DIR)) {
    fs.mkdirSync(STATIC_DIR, { recursive: true });
  }

  const batchData = JSON.parse(fs.readFileSync(BATCH_FILE, 'utf8'));
  const builders = [buildDay10, buildDay11, buildDay12, buildDay13, buildDay14];
  let allOk = true;

  for (const builder of builders) {
    const result = builder();
    const dayIndex = result.batchItem.day_index;
    const dayStr = String(dayIndex).padStart(3, '0');

    console.log(`\n${'='.repeat(60)}`);
    console.log(`Day ${dayIndex} (${result.batchItem.sub_area})`);
    console.log(`${'='.repeat(60)}`);
    console.log(`  지문 길이: ${result.totalLen}자 (목표 1400+-50)`);
    console.log(`  정독 스텝: ${result.content.payload.intensive.timeline.length}`);
    console.log(`  복기 카드: ${result.content.payload.recall.cards.length}`);
    console.log(`  확인 문항: ${result.content.payload.confirm.questions.length}`);

    const issues = [];
    const lenDiff = result.totalLen - 1400;
    if (Math.abs(lenDiff) > 50) {
      issues.push(`지문길이 ${result.totalLen}자 (차이 ${lenDiff > 0 ? '+' : ''}${lenDiff})`);
    }
    if (result.content.payload.recall.cards.length !== 8) {
      issues.push(`복기카드 ${result.content.payload.recall.cards.length}장 (8장 필요)`);
    }
    const confirmLen = result.content.payload.confirm.questions.length;
    if (confirmLen < 5 || confirmLen > 8) {
      issues.push(`확인학습 ${confirmLen}문항 (5~8 필요)`);
    }

    for (const step of result.content.payload.intensive.timeline) {
      const variance = validateChoiceVariance(step.question.choices);
      if (variance > 15) {
        issues.push(`${step.stepId} 선택지편차 ${variance}% (15% 이하 필요)`);
      }
    }

    if (issues.length > 0) {
      console.log(`  [경고] 검증 이슈:`);
      issues.forEach(i => console.log(`    - ${i}`));
      allOk = false;
    } else {
      console.log(`  [통과] 모든 검증 통과`);
    }

    batchData.items[dayIndex - 1] = result.batchItem;
    console.log(`  -> 배치 items[${dayIndex - 1}] 교체 완료`);

    const staticFile = path.join(STATIC_DIR, `${dayStr}.json`);
    fs.writeFileSync(staticFile, JSON.stringify(result.content, null, 2), 'utf8');
    console.log(`  -> ${dayStr}.json 생성 완료`);
  }

  fs.writeFileSync(BATCH_FILE, JSON.stringify(batchData, null, 2), 'utf8');
  console.log(`\n${'='.repeat(60)}`);
  console.log(`배치 파일 저장 완료`);
  console.log(`${'='.repeat(60)}`);

  if (allOk) {
    console.log('\n모든 Day(10~14) 검증 통과 및 파일 생성 완료!');
  } else {
    console.log('\n일부 검증 이슈가 있습니다. 위 로그를 확인하세요.');
    process.exit(1);
  }
}

main();

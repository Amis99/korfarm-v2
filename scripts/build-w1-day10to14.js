// === 유틸리티 함수 ===
function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`문단 ${pid} 없음`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText}" not found in ${pid}`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function sentenceRange(paragraphs, pid, sentIdx) {
  const para = paragraphs.find(p => p.id === pid);
  const sents = findSentences(para.text);
  if (sentIdx < 0 || sentIdx >= sents.length) throw new Error(`${pid} 문장 인덱스 ${sentIdx} 초과 (총 ${sents.length}문장)`);
  return { paragraphId: pid, start: sents[sentIdx].start, end: sents[sentIdx].end };
}

function fullParaRange(paragraphs, pid) {
  const para = paragraphs.find(p => p.id === pid);
  return { paragraphId: pid, start: 0, end: para.text.length };
}

function validateChoiceVariance(choices) {
  const lengths = choices.map(c => c.text.length);
  const mx = Math.max(...lengths), mn = Math.min(...lengths);
  if (mx === 0) return 0;
  return Math.round(((mx - mn) / mx) * 100);
}


function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`단락 ${pid}을(를) 찾을 수 없음`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText.substring(0,30)}..." 을(를) ${pid}에서 찾을 수 없음`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function makeIntensiveStep(stepId, paragraphs, pid, searchText, prompt, choices, answerId) {
  return {
    stepId,
    highlight: { ranges: [findRange(paragraphs, pid, searchText)] },
    question: {
      prompt,
      choices: choices.map(([id, text]) => ({ id, text })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeSummaryStep(stepId, paragraphs, pid, prompt, choices, answerId) {
  const para = paragraphs.find(p => p.id === pid);
  return {
    stepId,
    highlight: { ranges: [{ paragraphId: pid, start: 0, end: para.text.length }] },
    question: {
      prompt,
      choices: choices.map(([id, text]) => ({ id, text })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeRecallCards(paragraphs, count) {
  const full = paragraphs.map(p => p.text).join('\n');
  const totalLen = full.length;
  const chunkSize = Math.ceil(totalLen / count);
  const cards = [];
  for (let i = 0; i < count; i++) {
    const start = i * chunkSize;
    const end = Math.min(start + chunkSize, totalLen);
    cards.push({ id: `c${i+1}`, text: full.substring(start, end) });
  }
  return {
    cards,
    correctOrder: cards.map(c => c.id),
    seedPenalty: 1
  };
}

function makeConfirmQ(id, prompt, paragraphs, pid, answerTexts) {
  return {
    id,
    prompt,
    answerRanges: answerTexts.map(t => findRange(paragraphs, pid, t)),
    scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 },
    revealOnWrong: true,
    answerMatchMode: "ANY"
  };
}


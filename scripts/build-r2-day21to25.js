// ── 메인 ──
function main() {
  console.log('=== 러셀2 Day 21~25 빌드 시작 ===');

  const days = [
    { idx: 21, build: buildDay21 },
    { idx: 22, build: buildDay22 },
    { idx: 23, build: buildDay23 },
    { idx: 24, build: buildDay24 },
    { idx: 25, build: buildDay25 },
  ];

  const contents = days.map(d => {
    const content = d.build();
    return { idx: d.idx, content };
  });

  // 배치 파일 업데이트
  const batch = JSON.parse(fs.readFileSync(BATCH, 'utf8'));
  for (const { idx, content } of contents) {
    const subArea = idx % 2 === 1 ? "NONFICTION" : "LITERATURE";
    batch.items[idx - 1] = wrapBatchItem(idx, subArea, content);
  }
  fs.writeFileSync(BATCH, JSON.stringify(batch, null, 2), 'utf8');
  console.log(`\n배치 파일 업데이트 완료: items[20]~[24]`);

  // static 파일 생성
  for (const { idx, content } of contents) {
    const fname = String(idx).padStart(3, '0') + '.json';
    const fpath = path.join(STATIC_DIR, fname);
    fs.writeFileSync(fpath, JSON.stringify(content, null, 2), 'utf8');
    console.log(`static 파일 생성: ${fname}`);
  }

  // 검증
  console.log('\n=== 검증 ===');
  let allOk = true;
  for (const { idx, content } of contents) {
    const errors = [];
    const p = content.payload;
    const totalLen = p.passage.paragraphs.reduce((s, pg) => s + pg.text.length, 0);

    if (totalLen < 1150 || totalLen > 1250) errors.push(`지문 길이 ${totalLen}자 (범위 밖)`);
    if (content.timeLimitSec !== 480) errors.push(`timeLimitSec=${content.timeLimitSec}`);
    if (content.schoolGradeRange.max !== 9) errors.push(`schoolGradeRange.max=${content.schoolGradeRange.max}`);
    if (p.recall.cards.length !== 8) errors.push(`복기 카드 ${p.recall.cards.length}장`);
    if (p.recall.seedPenalty !== 1) errors.push(`seedPenalty=${p.recall.seedPenalty}`);
    if (p.confirm.questions.length < 5 || p.confirm.questions.length > 8) errors.push(`확인 문항 ${p.confirm.questions.length}개`);

    // 확인 문제 형식 검증
    for (const q of p.confirm.questions) {
      if (q.answerMatchMode !== "ANY") errors.push(`${q.id}: answerMatchMode != ANY`);
      if (q.revealOnWrong !== true) errors.push(`${q.id}: revealOnWrong != true`);
      if (q.scoring.correctDeltaSec !== 30) errors.push(`${q.id}: correctDeltaSec != 30`);
      if (q.scoring.wrongDeltaSec !== -45) errors.push(`${q.id}: wrongDeltaSec != -45`);
    }

    // subArea 검증
    const expectedSub = idx % 2 === 1 ? "NONFICTION" : "LITERATURE";
    if (content.subArea !== expectedSub) errors.push(`subArea=${content.subArea} (기대: ${expectedSub})`);

    if (errors.length > 0) {
      console.log(`  Day ${idx}: NG - ${errors.join(', ')}`);
      allOk = false;
    } else {
      console.log(`  Day ${idx}: OK (${totalLen}자, 정독 ${p.intensive.timeline.length}스텝, 복기 ${p.recall.cards.length}장, 확인 ${p.confirm.questions.length}문항)`);
    }
  }

  console.log(allOk ? '\n모든 검증 통과!' : '\n일부 검증 실패!');
}

main();

// === 유틸리티 함수 ===
function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`문단 ${pid} 없음`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText.substring(0,30)}..." not found in ${pid}`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function sentenceRange(paragraphs, pid, sentIdx) {
  const para = paragraphs.find(p => p.id === pid);
  const sents = findSentences(para.text);
  if (sentIdx < 0 || sentIdx >= sents.length) throw new Error(`${pid} 문장 인덱스 ${sentIdx} 초과 (총 ${sents.length}문장)`);
  return { paragraphId: pid, start: sents[sentIdx].start, end: sents[sentIdx].end };
}

function fullParaRange(paragraphs, pid) {
  const para = paragraphs.find(p => p.id === pid);
  return { paragraphId: pid, start: 0, end: para.text.length };
}

function makeStep(stepId, ranges, prompt, choices, answerId) {
  return {
    stepId,
    highlight: { ranges: Array.isArray(ranges) ? ranges : [ranges] },
    question: {
      prompt,
      choices: choices.map((t, i) => ({ id: String.fromCharCode(65 + i), text: t })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeConfirm(id, prompt, answerRanges) {
  return {
    id, prompt,
    answerMatchMode: "ANY",
    answerRanges: Array.isArray(answerRanges) ? answerRanges : [answerRanges],
    scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 },
    revealOnWrong: true
  };
}

function buildContent(dayIndex, subArea, title, paragraphs, timeline, recallCards, confirmQuestions) {
  const dayStr = String(dayIndex).padStart(3, '0');
  const content = {
    contentId: `dr-w2-${dayStr}`,
    contentType: "DAILY_READING",
    version: 1,
    status: "PUBLISHED",
    title,
    description: "일일 독해 - 정독·복기·확인",
    targetLevel: "WITTGENSTEIN_2",
    schoolGradeRange: { min: 10, max: 11 },
    area: "READING",
    subArea,
    competencies: ["READING"],
    tags: ["daily"],
    access: { mode: "FREE" },
    seedReward: { seedType: "WHEAT", count: 3, multiplier: 1 },
    timeLimitSec: 480,
    assets: {},
    payload: {
      passage: { format: "TEXT", paragraphs },
      intensive: { timeline },
      recall: {
        cards: recallCards,
        correctOrder: recallCards.map(c => c.id),
        seedPenalty: 1
      },
      confirm: { questions: confirmQuestions }
    }
  };

  const batchItem = {
    content_type: "DAILY_READING",
    level_id: "WITTGENSTEIN_2",
    area: "READING",
    sub_area: subArea,
    day_index: dayIndex,
    module_key: "reading_training",
    schema_version: "1.0",
    content
  };

  return { content, batchItem };
}


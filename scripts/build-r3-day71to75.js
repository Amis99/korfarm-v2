function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && text[next] === ' ') next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`문단 ${pid}를 찾을 수 없습니다.`);
  const start = para.text.indexOf(searchText);
  if (start === -1) throw new Error(`"${searchText.substring(0, 30)}..." not found in ${pid}`);
  return { paragraphId: pid, start, end: start + searchText.length };
}

function findAllRanges(paragraphs, searchText) {
  const ranges = [];
  for (const para of paragraphs) {
    let idx = 0;
    while (true) {
      const found = para.text.indexOf(searchText, idx);
      if (found === -1) break;
      ranges.push({ paragraphId: para.id, start: found, end: found + searchText.length });
      idx = found + 1;
    }
  }
  if (ranges.length === 0) throw new Error(`"${searchText}" 를 지문 어디에서도 찾을 수 없습니다.`);
  return ranges;
}

function charLen(text) {
  return text.length;
}

function hashIdx(dayIndex) {
  return dayIndex - 1;
}

function truncate(text, maxLen) {
  if (text.length <= maxLen) return text;
  return text.substring(0, maxLen) + '...';
}

function shuffleChoices(choices) {
  const arr = [...choices];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function buildTimeline(stepId, ranges, prompt, choices, answerId) {
  return {
    stepId,
    highlight: { ranges },
    question: {
      prompt,
      choices: choices.map((t, i) => ({ id: ['A','B','C','D'][i], text: t })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function buildRecallCards(texts) {
  return {
    cards: texts.map((t, i) => ({ id: `c${i+1}`, text: t })),
    correctOrder: texts.map((_, i) => `c${i+1}`),
    seedPenalty: 1
  };
}

function makeConfirmQ(id, prompt, paragraphs, searchText) {
  return {
    id,
    prompt,
    answerRanges: findAllRanges(paragraphs, searchText),
    scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 },
    revealOnWrong: true,
    answerMatchMode: 'ANY'
  };
}

function assembleFull(dayIndex, subArea, paragraphTexts, intensiveSteps, recallCardTexts, confirmQuestions) {
  const dayStr = String(dayIndex).padStart(3, '0');
  const isLit = subArea === 'LITERATURE';
  const subAreaKo = isLit ? '문학' : '비문학';
  const title = `일일 독해(러셀 3) Day ${dayIndex} ${subAreaKo}`;
  const paragraphs = paragraphTexts.map((t, i) => ({ id: `p${i+1}`, text: t }));

  return {
    contentId: `dr-r3-${dayStr}`,
    contentType: 'DAILY_READING',
    version: 1,
    status: 'PUBLISHED',
    title,
    description: '일일 독해 - 정독·복기·확인',
    targetLevel: 'RUSSELL_3',
    schoolGradeRange: { min: 9, max: 10 },
    area: 'READING',
    subArea: subArea,
    competencies: ['READING'],
    tags: ['daily'],
    access: { mode: 'FREE' },
    seedReward: { seedType: 'WHEAT', count: 3, multiplier: 1 },
    timeLimitSec: 480,
    assets: {},
    payload: {
      passage: { format: 'TEXT', paragraphs },
      intensive: { timeline: intensiveSteps },
      recall: buildRecallCards(recallCardTexts),
      confirm: { questions: confirmQuestions }
    }
  };
}


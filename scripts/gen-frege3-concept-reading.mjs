// 배치 JSON 생성
function truncateText(text, maxLen = 40) {
  if (text.length <= maxLen) return text;
  return text.substring(0, maxLen) + '...';
}

function buildItem(ch) {
  const paragraphs = ch.paragraphs.map((text, i) => ({
    id: `p${i + 1}`,
    text
  }));

  const timeline = ch.paragraphs.map((text, i) => ({
    stepId: `int-${i + 1}`,
    highlight: {
      ranges: [{
        paragraphId: `p${i + 1}`,
        start: 0,
        end: Math.min(50, text.length)
      }]
    },
    question: {
      prompt: ch.questions[i].prompt,
      choices: ch.questions[i].choices,
      answerId: ch.questions[i].answerId,
      scoring: {
        correctDeltaSec: 15,
        wrongDeltaSec: -15
      }
    }
  }));

  const cards = ch.paragraphs.map((text, i) => ({
    id: `rc-${i + 1}`,
    front: truncateText(text),
    back: text
  }));

  return {
    contentType: "PRO_READING",
    levelId: "FREGE_3",
    area: "READING",
    subArea: "개념",
    dayIndex: ch.dayIndex,
    moduleKey: "reading_training",
    schemaVersion: "1.0",
    content: {
      contentType: "PRO_READING",
      title: ch.title,
      targetLevel: "FREGE_3",
      area: "READING",
      subArea: "개념",
      timeLimitSec: 300,
      seedReward: {
        seedType: "seed_rice",
        count: 3,
        multiplier: 1
      },
      payload: {
        passage: { paragraphs },
        intensive: { timeline },
        recall: { cards },
        confirm: { questions: [] }
      }
    }
  };
}


function findSentences(text) {
  const sentences = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '.' && (i === text.length - 1 || text[i+1] === ' ' || text[i+1] === '\n')) {
      sentences.push({ start, end: i + 1, text: text.substring(start, i + 1) });
      let next = i + 1;
      while (next < text.length && (text[next] === ' ' || text[next] === '\n')) next++;
      start = next;
    }
  }
  if (start < text.length) sentences.push({ start, end: text.length, text: text.substring(start) });
  return sentences;
}

function findRange(paragraphs, pid, searchText) {
  const para = paragraphs.find(p => p.id === pid);
  if (!para) throw new Error(`단락 ${pid} 없음`);
  const idx = para.text.indexOf(searchText);
  if (idx === -1) throw new Error(`"${searchText}" not found in ${pid}`);
  return { paragraphId: pid, start: idx, end: idx + searchText.length };
}

function makeContent(dayIndex, subArea, paragraphs, timeline, cards, questions) {
  const num = String(dayIndex).padStart(3, '0');
  return {
    contentId: `dr-w1-${num}`, contentType: 'DAILY_READING', version: 1, status: 'PUBLISHED',
    title: `일일 독해(비트겐슈타인 1) Day ${dayIndex} ${subArea === 'LITERATURE' ? '문학' : '비문학'}`,
    description: '일일 독해 - 정독·복기·확인', targetLevel: 'WITTGENSTEIN_1',
    schoolGradeRange: { min: 9, max: 10 }, area: 'READING', subArea,
    competencies: ['READING'], tags: ['daily'], access: { mode: 'FREE' },
    seedReward: { seedType: 'WHEAT', count: 3, multiplier: 1 },
    timeLimitSec: 480, assets: {},
    payload: {
      passage: { format: 'TEXT', paragraphs },
      intensive: { timeline },
      recall: { cards, correctOrder: cards.map(c => c.id), seedPenalty: 1 },
      confirm: { questions }
    }
  };
}

function makeBatchItem(dayIndex, subArea, content) {
  return { content_type: 'DAILY_READING', level_id: 'WITTGENSTEIN_1', area: 'READING', sub_area: subArea, day_index: dayIndex, module_key: 'reading_training', schema_version: '1.0', content };
}

function q(id, prompt, pid, searchText, paragraphs) {
  const r = findRange(paragraphs, pid, searchText);
  return { id, prompt, answerText: searchText, answerMatchMode: 'ANY', answerRanges: [r], scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 }, revealOnWrong: true };
}

function S(stepId, pid, s, e, prompt, choices, answerId) {
  return { stepId, highlight: { ranges: [{ paragraphId: pid, start: s, end: e }] }, question: { prompt, choices: choices.map((t,i) => ({ id: ['A','B','C','D'][i], text: t })), answerId, scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true } } };
}


function makeIntensiveStep(stepId, ranges, prompt, choices, answerId) {
  return {
    stepId,
    highlight: { ranges },
    question: {
      prompt,
      choices: choices.map((t, i) => ({ id: ['A','B','C','D'][i], text: t })),
      answerId,
      scoring: { correctDeltaSec: 20, wrongDeltaSec: -40, eliminateWrongChoice: true }
    }
  };
}

function makeConfirmQ(id, prompt, paragraphs, searchText) {
  return {
    id,
    prompt,
    answerRanges: findAllRanges(paragraphs, searchText),
    scoring: { correctDeltaSec: 30, wrongDeltaSec: -45 },
    revealOnWrong: true,
    answerMatchMode: 'ANY'
  };
}

function buildTimeline(paragraphs, steps) {
  return steps.map((step, i) => {
    const stepId = `s${i + 1}`;
    return makeIntensiveStep(stepId, step.ranges, step.prompt, step.choices, step.answerId);
  });
}

function buildRecallCards(cardTexts) {
  return cardTexts.map((t, i) => ({ id: `c${i+1}`, text: t }));
}


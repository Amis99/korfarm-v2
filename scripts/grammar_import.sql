## **명사는 사용 범위에 따라 고유 명사와 보통 명사로 구분할 수 있어. 일반적인 대상을 가리키는 명사는 보통 명사고, 고유한 것을 가리키는 명사가 고유 명사야. 고유 명사에는 사람 이름, 지역 이름, 상표 이름 등이 속해, 예를 들면, ''학교''는 보통 명사이지만, ''서울대학교''는 고유 명사야.**

또한 명사는 홀로 쓰일 수 있느냐 없느냐에 따라서 자립 명사와 의존 명사로 분류할 수도 있어. 혼자서 쓰일 수 있는 명사를 자립 명사라고 하고, 앞에 꾸미는 말이 필요한 명사를 의존 명사라고 해. ''책'', ''홍길동'', ''계산기'' 등 우리가 떠올리는 명사 중에 대부분은 아마 자립 명사일 거야. 의존 명사에는 ''것'', ''수'' ‘리’ 등이 있어. ''것''과 ''수''는 홀로 쓰일 수 없고, ''맛있는 것'', ''읽을 수 있다'', ‘그럴 리가 없다’와 같이 반드시 꾸미는 말이 앞에 와야만 쓰일 수 있지.

대명사는 사물, 사람, 장소 등의 이름을 대신하여 가리키는 단어야. 대명사는 그것이 가리키는 대상에 따라 크게 인칭 대명사와 지시 대명사로 구분할 수 있어. 인칭 대명사는 사람의 이름을 대신하여 가리키는 단어야. 누구를 가리키느냐에 따라 1인칭 대명사(나, 저, 우리, 저희 등), 2인칭 대명사(너, 그대, 너희 등), 3인칭 대명사(그, 그들, 이들, 저들 등)로 나뉘지. 지시 대명사는 사물이나 장소의 이름을 대신해서 가리키는 단어야. ''이것, 그것, 저것, 여기, 거기, 저기'' 등이 있어.


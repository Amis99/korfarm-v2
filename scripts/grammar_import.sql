**◇ 품사**  
품사는 **단어**에 붙어 있는 라벨이다.  
단어는 **사전**에 수록되어 있다.  
**사전**에서 단어를 찾으면 그 단어의 품사가 적혀 있다.  
따라서 단어의 품사를 알고 싶을 때에는 그 단어를  
**사전**에서 찾을 때 어떤 형태로 찾을지부터 생각하도록 하자.

**◇ 품사를 분류하는 순서**

1. 앞말에 붙여 썼는가? (Yes) → **조사** (관계언)  
   (No) ↓  
2. 사전을 찾을 때 ‘-다’를 붙여 찾는가? (Yes) →  
   1. 어간에 ‘-ㄴ다’나 ‘-는다’를 붙여쓸 수 있는가? (Yes) → **동사** (용언)  
      (No) ↓  
   2. **형용사** (용언)  
      (No) ↓  
3.   
4. 뒤에 ‘이/가’, ‘을/를’, ‘에’를 붙일 수 있는가? (Yes) →  
   1. 양이나 순서를 나타내는가? (Yes) → **수사** (체언)  
      (No) ↓  
   2. 영어로 번역했을 때 I you he they 등인가? (Yes) → **대명사** (체언)  

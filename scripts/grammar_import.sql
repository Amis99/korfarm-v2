**◇ 활용**  
활용은 **어간** 에 **어미** 가 붙는 것이다.  
어간은 **기본형** 에서 ‘-다’ 만 덜어낸 부분을 말한다.  
기본형은 **사전** 찾을 말이다.  
어미는 **어간** 뒤에 붙는 ‘-다’ 또는 ‘-다’ 대신 쓰인 말이다.  
어간에는 여러 개의 **어미** 가 붙을 수 있다.

1. 뒤에 또다른 어미가 오는가? (Yes) → **선어말 어미** (선어말 어미)  
   (No) ↓  
2. 문장을 끝내는가? (Yes) → **종결 어미** (어말 어미)  
   (No) ↓  
3. 문장이나 단어를 이어주는가? (Yes) → **연결 어미** (어말 어미)  
   (No) ↓  
4. 단어를 다른 품사처럼 쓰이게 하는가? (Yes) → **전성 어미** (어말 어미)

**◇ 활용의 옷 입기 비유**

* 서로 대응되는 표현끼리 줄을 그어 보시오.  
  * 어간 ↔ 사람의 몸  
  * 어미 ↔ 옷  
  * 가장 겉에 입는 옷 ↔ 어말 어미  
  * 겉옷 안에 입는 옷 ↔ 선어말 어미  
  * 어미 없이 어간 홀로 쓰여선 안 된다. ↔ 발가벗고 다녀선 안 된다.  
  * 어간 없이 어미 홀로 쓰여선 안 된다. ↔ 옷만 둥둥 떠다녀선 안 된다.  
  * 어미는 어간 뒤에 여러 개가 붙을 수 있다. ↔ 옷은 여러 벌 겹쳐 입을 수 있다.


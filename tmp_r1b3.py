def make_choices(correct_text, distractor_texts, seed):
    distractors = []
    seen = {correct_text}
    for text in distractor_texts + GENERIC_WRONGS:
        if text not in seen:
            distractors.append(text)
            seen.add(text)
        if len(distractors) == 3:
            break
    correct_idx = seed % 4
    choices = []
    wrong_iter = iter(distractors)
    for idx, label in enumerate(CHOICE_LABELS):
        text = correct_text if idx == correct_idx else next(wrong_iter)
        choices.append({"id": label, "text": text})
    return choices, CHOICE_LABELS[correct_idx]


def build_payload(file_spec):
    paragraph_texts = {}
    paragraph_ranges = {}
    timeline = []
    step_index = 1
    summary_texts = [p["summary"] for p in file_spec["paragraphs"]]
    all_sentence_paraphrases = [
        paraphrase
        for paragraph in file_spec["paragraphs"]
        for paraphrase in paragraph["paraphrases"]
    ]
    for p_idx, paragraph in enumerate(file_spec["paragraphs"]):
        pid = paragraph["id"]
        sentences = paragraph["sentences"]
        paraphrases = paragraph["paraphrases"]
        joined = " ".join(sentences)
        paragraph_texts[pid] = joined
        paragraph_ranges[pid] = {"start": 0, "end": len(joined)}
        cursor = 0
        local_pool = [text for text in paraphrases]
        global_pool = [text for text in all_sentence_paraphrases if text not in local_pool]
        for s_idx, sentence in enumerate(sentences):
            start = cursor
            end = cursor + len(sentence)
            cursor = end + 1
            correct = paraphrases[s_idx]
            distractors = [text for text in local_pool if text != correct]
            if len(distractors) < 3:
                distractors += global_pool
            prompt = "이 문장에서 드러나는 내용으로 가장 알맞은 것은?" if (s_idx == 0 and p_idx == 0) else ("앞의 흐름에 이어 이 문장에서 드러나는 내용으로 가장 알맞은 것은?" if s_idx == 0 else "앞의 내용을 다시 떠올리며 보면 이 문장의 뜻으로 가장 알맞은 것은?")
            choices, answer_id = make_choices(correct, distractors, step_index - 1)
            timeline.append({"stepId": f"s{step_index}", "highlight": {"ranges": [{"paragraphId": pid, "start": start, "end": end}]}, "question": {"prompt": prompt, "choices": choices, "answerId": answer_id, "scoring": {"correctDeltaSec": 20, "wrongDeltaSec": -40, "eliminateWrongChoice": True}}})
            step_index += 1
        summary_distractors = [text for text in summary_texts if text != paragraph["summary"]]
        summary_choices, summary_answer_id = make_choices(paragraph["summary"], summary_distractors, step_index - 1)
        timeline.append({"stepId": f"s{step_index}", "highlight": {"ranges": [{"paragraphId": pid, "start": 0, "end": len(joined)}]}, "question": {"prompt": "이 문단을 가장 잘 묶는 설명은 무엇인가?", "choices": summary_choices, "answerId": summary_answer_id, "scoring": {"correctDeltaSec": 20, "wrongDeltaSec": -40, "eliminateWrongChoice": True}}})
        step_index += 1
    recall_cards = [{"id": f"c{i+1}", "text": t} for i, t in enumerate(file_spec["recall"])]
    confirm_questions = []
    for qid, prompt, pids, mode in file_spec["confirm"]:
        confirm_questions.append({"id": qid, "prompt": prompt, "answerRanges": [{"paragraphId": pid, "start": 0, "end": paragraph_ranges[pid]["end"]} for pid in pids], "scoring": {"correctDeltaSec": 30, "wrongDeltaSec": -45}, "revealOnWrong": True, "answerMatchMode": mode})
    return {
        "passage": {"format": "TEXT", "paragraphs": [{"id": p["id"], "text": paragraph_texts[p["id"]]} for p in file_spec["paragraphs"]]},
        "intensive": {"timeline": timeline},
        "recall": {"cards": recall_cards, "correctOrder": [c["id"] for c in recall_cards], "seedPenalty": 1},
        "confirm": {"questions": confirm_questions},
    }



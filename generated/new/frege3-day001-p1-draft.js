// 프레게3 Day 1 p1 재구성 - 문장별 정확한 글자수 맞추기
// 목표: [74, 54, 63, 50, 54, 29, 81, 51] 총 456자

const targets = [74, 54, 63, 50, 54, 29, 81, 51];

const sentences = [
  // s1 (74자): 과학의 모형 정의 - "중요한 관계를 골라 단순하게 만든 표현"
  "과학에서 모형이란, 복잡한 대상이나 현상 가운데 중요한 관계만을 골라내어 사람이 이해하기 쉬운 방식으로 단순하게 만든 표현을 뜻한다.",
  // s2 (54자): 지구본이 대륙의 위치와 바다의 넓이를 눈으로 익히게 해 줌
  "예를 들어 지구본은 넓고 둥근 지구에서 대륙의 위치와 바다의 넓이를 눈으로 직접 익히게 해 준다.",
  // s3 (63자): 원자 모형은 보이지 않는 구조를 설명하려고 만든 생각의 틀
  "맨눈에 보이지 않는 원자의 구조를 설명하려고 그림이나 공의 배열로 나타내는 원자 모형도 역시 생각의 틀에 가깝다.",
  // s4 (50자): 실제와 달라도 핵심 특징을 뽑아내어 이해를 돕기 때문에 쓸모 있다
  "이처럼 모형은 실제 모습과는 달라도 핵심 특징을 뽑아내어 이해를 돕기 때문에 쓸모가 크다.",
  // s5 (54자): 모형은 배우려는 대상을 한눈에 붙잡게 해 주는 장치
  "다시 말하면, 모형은 배우려는 대상의 중요한 모습을 한눈에 붙잡게 해 주는 편리한 장치인 셈이다.",
  // s6 (29자): 모형이 빼고 있는 부분을 잊어버릴 때 문제 발생
  "다만 모형이 빼고 있는 부분을 잊으면 문제가 생긴다.",
  // s7 (81자): 모형에 없는 정보까지 실제처럼 안다고 믿는 오해의 예시
  "지구본만 보고 실제 땅의 높낮이나 온도, 냄새까지 다 안다고 여기는 사람이 있다면, 그것은 모형에 없는 정보를 실제처럼 믿는 잘못에 빠진 것이다.",
  // s8 (51자): 무엇을 잘 보여 주고 무엇을 덜어 냈는지 함께 따져야
  "그러므로 모형을 볼 때에는 무엇을 잘 보여 주고 무엇을 덜어 냈는지를 꼭 함께 따져야 한다."
];

let totalOk = true;
for (let i = 0; i < sentences.length; i++) {
  const len = sentences[i].length;
  const diff = len - targets[i];
  const ok = diff === 0;
  if (!ok) totalOk = false;
  console.log(`s${i+1}: ${len}자 (목표 ${targets[i]}, ${diff > 0 ? '+' : ''}${diff}) ${ok ? '✅' : '❌'}`);
}
console.log(`\n총 글자수: ${sentences.reduce((s, t) => s + t.length, 0)} (목표 456)`);
console.log(`전체 통과: ${totalOk ? '✅' : '❌'}`);

if (!totalOk) {
  console.log('\n=== 조정 필요 ===');
  for (let i = 0; i < sentences.length; i++) {
    const diff = sentences[i].length - targets[i];
    if (diff !== 0) {
      console.log(`s${i+1}: ${diff > 0 ? diff + '자 줄여야' : Math.abs(diff) + '자 늘려야'} 함`);
      console.log(`  현재: "${sentences[i]}"`);
    }
  }
}

// 소쉬르1 Day 78 p1 재구성
const targets = [42, 37, 37, 32, 34, 42, 43]; // 267자 총합

const sentences = [
  // s1 (42자): 소연이 창가 유리의 별 스티커 하나를 봄
  "교실 정리를 하던 소연이 창가 유리에 붙어 있는 별 스티커 하나를 보았어요.",
  // s2 (37자): 파란 별 끝이 살짝 들려 있었음
  "그런데 그 예쁜 파란 별의 끝이 한쪽만 살짝 들려 올라와 있었어요.",
  // s3 (37자): 종이 끝을 손톱 대신 자로 살짝 들었다
  "소연은 유리가 긁힐까 봐 손톱 대신 자를 넣어 끝을 살짝 들었어요.",
  // s4 (32자): 끝이 더 뜨지 않게 살살 눌러야 한다고 했다
  "민지는 끝이 더 뜨지 않게 살살 눌러야만 한다고 말했어요.",
  // s5 (34자): 마른 휴지로 유리 면을 살살 닦았어요
  "그래서 두 사람은 먼저 마른 휴지로 유리 면을 살살 닦았어요.",
  // s6 (42자): 소연은 윗부분을 잡고 민지는 아래쪽을 맞추었어요
  "소연이는 별 스티커의 윗부분을 손가락으로 잡고, 민지는 아래쪽을 맞추었어요.",
  // s7 (43자): 파란 별이 비뚤어지지 않았는지 같이 보았어요
  "그리고 나서 두 사람은 파란 별이 비뚤어지지 않았는지를 같이 확인해 보았어요."
];

for (let i = 0; i < sentences.length; i++) {
  const len = sentences[i].length;
  const diff = len - targets[i];
  const ok = diff === 0;
  console.log(`s${i+1}: ${len}자 (목표 ${targets[i]}, ${diff > 0 ? '+' : ''}${diff}) ${ok ? '✅' : '❌'}`);
}
console.log(`\n총: ${sentences.reduce((s, t) => s + t.length, 0)} (목표 267)`);

export function getSchemaForLevel(levelId) {
  if (!levelId) return RUSSELL_SCHEMA;
  if (levelId.startsWith("saussure")) return SAUSSURE_SCHEMA;
  if (levelId === "frege1" || levelId === "frege2") return FREGE_SCHEMA;
  if (levelId === "frege3") return FREGE3_SCHEMA;
  return RUSSELL_SCHEMA; // russell1~3, wittgenstein1~3
}


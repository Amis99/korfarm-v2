for (let fileId in passages) {
  const passage = passages[fileId];
  let output = '=== ' + fileId + ' ===\n';
  
  for (let id in passage) {
    output += '[' + id + ']\n';
    const sentences = passage[id].match(/[^.!?]+[.!?]/g);
    let start = 0;
    sentences.forEach((s, i) => {
      const sTrim = s.trim();
      const sStart = passage[id].indexOf(sTrim, start);
      const sEnd = sStart + sTrim.length - 1;
      output += 's' + (i + 1) + ': ' + sStart + '-' + sEnd + '\n';
      start = sEnd + 1;
    });
    output += 'p_all: 0-' + (passage[id].length - 1) + '\n';
  }
  
  keywords[fileId].forEach(word => {
    output += 'Keyword [' + word + ']:\n';
    for (let id in passage) {
      let pos = passage[id].indexOf(word);
      while (pos !== -1) {
        output += '  { "paragraphId": "' + id + '", "start": ' + pos + ', "end": ' + (pos + word.length - 1) + ' },\n';
        pos = passage[id].indexOf(word, pos + 1);
      }
    }
  });
  
  fs.writeFileSync('indices_' + fileId + '.txt', output, 'utf8');
}

const fs = require('fs');
function set(file, stepId, choiceId, text){
  const p = `./frege1/${file}.json`;
  const data = JSON.parse(fs.readFileSync(p,'utf8'));
  data.payload.intensive.timeline.find(s=>s.stepId===stepId).question.choices.find(c=>c.id===choiceId).text = text;
  fs.writeFileSync(p, JSON.stringify(data,null,2)+'\n');
}

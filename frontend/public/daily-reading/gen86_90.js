data.forEach(d => {
  const filename = 'frege1/' + d.id.padStart(3, '0') + '.json';
  
  const paragraphs = d.passages.map((text, i) => ({ id: "p" + (i + 1), text }));
  
  const timeline = [];
  let qsIndex = 0;
  d.passages.forEach((text, pIndex) => {
    const sentences = text.match(/[^.!?]+[.!?]+/g) || [text];
    let start = 0;
    sentences.forEach((s) => {
      const sTrim = s.trim();
      const sStart = text.indexOf(sTrim, start);
      const sEnd = sStart + sTrim.length - 1;
      
      const q = d.qs[qsIndex++];
      timeline.push({
        stepId: "s" + qsIndex,
        highlight: { ranges: [{ paragraphId: "p" + (pIndex + 1), start: sStart, end: sEnd }] },
        question: {
          prompt: q.p,
          choices: q.c.map((text, i) => ({ id: String.fromCharCode(65 + i), text })),
          answerId: "A",
          scoring: { correctDeltaSec: 10, wrongDeltaSec: -5, eliminateWrongChoice: false }
        }
      });
      start = sEnd + 1;
    });
    
    // Summary question
    const sumQ = d.qs[qsIndex++];
    timeline.push({
      stepId: "s" + qsIndex,
      highlight: { ranges: [{ paragraphId: "p" + (pIndex + 1), start: 0, end: text.length - 1 }] },
      question: {
        prompt: sumQ.p,
        choices: sumQ.c.map((text, i) => ({ id: String.fromCharCode(65 + i), text })),
        answerId: "A",
        scoring: { correctDeltaSec: 10, wrongDeltaSec: -5, eliminateWrongChoice: false }
      }
    });
  });

  const cards = d.recall.map((text, i) => ({ id: "c" + (i + 1), text }));
  const correctOrder = cards.map(c => c.id);

  const confirmQs = d.confirm.map((cq, i) => {
    const ranges = [];
    d.passages.forEach((text, pIndex) => {
      let pos = text.indexOf(cq.a);
      while (pos !== -1) {
        ranges.push({ paragraphId: "p" + (pIndex + 1), start: pos, end: pos + cq.a.length - 1 });
        pos = text.indexOf(cq.a, pos + 1);
      }
    });
    return {
      id: "q" + (i + 1),
      prompt: cq.p,
      answerText: cq.a,
      answerMatchMode: "EXACT",
      answerRanges: ranges,
      scoring: { correctDeltaSec: 10, wrongDeltaSec: -5, eliminateWrongChoice: false },
      revealOnWrong: true
    };
  });

  const result = {
    contentId: "dr-frege1-" + d.id.padStart(3, '0'),
    contentType: "DAILY_READING",
    version: 1,
    status: "PUBLISHED",
    title: d.title,
    description: d.desc,
    targetLevel: "FREGE_1",
    schoolGradeRange: { min: 4, max: 4 },
    area: "국어",
    subArea: "독해",
    competencies: ["사실적 이해", "비판적 이해"],
    tags: d.tags,
    access: { mode: "FREE" },
    seedReward: { seedType: "GOLD", count: 10, multiplier: 1 },
    timeLimitSec: 900,
    assets: {},
    payload: {
      passage: { format: "TEXT", paragraphs },
      intensive: { timeline },
      recall: { cards, correctOrder, seedPenalty: 2 },
      confirm: { questions: confirmQs }
    }
  };

  fs.writeFileSync(filename, JSON.stringify(result, null, 2), 'utf8');
  console.log("Wrote " + filename);
});
